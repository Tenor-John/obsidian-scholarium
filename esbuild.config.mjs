import esbuild from "esbuild";
import process from "process";
import { builtinModules } from "node:module";
import { staticDependencyPlugin } from "./scripts/esbuild-static-dependencies.mjs";

const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

const common = {
	banner: {
		js: banner,
	},
	bundle: true,
	plugins: [staticDependencyPlugin],
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules,
		...builtinModules.map((name) => `node:${name}`),
	],
	format: "cjs",
	target: "es2018",
	charset: "utf8",
	logLevel: "info",
	loader: {
		// Ketcher's stylesheet is embedded as text and installed by its runtime
		// module. No additional release assets or runtime style requests are needed.
		".css": "text",
		".less": "text",
	},
	alias: {
		// The full paper package includes PaperScript's runtime compiler. Ketcher
		// only needs paper-core; this removes the compiler instead of disguising it.
		paper: "paper/dist/paper-core.js",
	},
	define: {
		"process.env.NODE_ENV": prod ? '"production"' : '"development"',
		global: "globalThis",
	},
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	minify: false,
};

const mainContext = await esbuild.context({
	...common,
	entryPoints: ["src/main.ts"],
	format: "cjs",
	outfile: "main.js",
});

if (prod) {
	await mainContext.rebuild();
	process.exit(0);
} else {
	await mainContext.watch();
}
