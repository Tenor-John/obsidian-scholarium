"use strict";

/**
 * Embed the reviewed Scholarium logo in the three-file plugin bundle.
 *
 * A clean Obsidian install receives only main.js, manifest.json and styles.css.
 * Keeping the image as a data URL restores the real product mark without
 * reintroducing an unshipped assets/logo.png runtime dependency.
 */
const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");

const BEGIN = "/* SCHOLARIUM_LOGO_EMBED_BEGIN */";
const END = "/* SCHOLARIUM_LOGO_EMBED_END */";

function sha256(bytes) {
  return crypto.createHash("sha256").update(bytes).digest("hex");
}

function renderLogoBlock(bytes) {
  return [
    BEGIN,
    `/* source_sha256=${sha256(bytes)}; generated by tools/embed-logo.js */`,
    `var SCHOLARIUM_LOGO_DATA_URL = "data:image/png;base64,${bytes.toString("base64")}";`,
    END,
  ].join("\n");
}

function replaceBlock(source, block) {
  const start = source.indexOf(BEGIN);
  const finish = source.indexOf(END, start + BEGIN.length);
  if (start < 0 || finish < 0) throw new Error("main.js is missing the Scholarium logo embed markers");
  return source.slice(0, start) + block + source.slice(finish + END.length);
}

function embedLogo({ root = path.join(__dirname, "..") } = {}) {
  const logoPath = path.join(root, "assets", "logo.png");
  const mainPath = path.join(root, "main.js");
  const bytes = fs.readFileSync(logoPath);
  const before = fs.readFileSync(mainPath, "utf8");
  const after = replaceBlock(before, renderLogoBlock(bytes));
  fs.writeFileSync(mainPath, after, "utf8");
  return { logoPath, mainPath, sha256: sha256(bytes), bytes: bytes.length };
}

if (require.main === module) {
  const result = embedLogo();
  process.stdout.write(`embedded ${result.bytes} logo bytes (${result.sha256})\n`);
}

module.exports = { BEGIN, END, sha256, renderLogoBlock, replaceBlock, embedLogo };
