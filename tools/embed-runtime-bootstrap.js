"use strict";

/**
 * Mechanically embeds the reviewed runtime-bootstrap module in the frozen
 * Preview main.js.  BRAT installs only main.js/manifest.json/styles.css, so a
 * runtime require of tools/runtime-bootstrap.js would fail on a clean Vault.
 *
 * This tool is intentionally deterministic.  The generated block records the
 * source SHA-256 and is replaced in place on every run.
 */

const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");

const BEGIN = "/* SCHOLARIUM_RUNTIME_BOOTSTRAP_EMBED_BEGIN */";
const END = "/* SCHOLARIUM_RUNTIME_BOOTSTRAP_EMBED_END */";

function sha256(value) {
  return crypto.createHash("sha256").update(value).digest("hex");
}

function buildBlock(source) {
  const normalized = String(source).replace(/^\uFEFF/, "").replace(/^"use strict";\s*/, "");
  return `${BEGIN}\n` +
    `/* source_sha256=${sha256(source)}; generated by tools/embed-runtime-bootstrap.js */\n` +
    `var schRuntimeBootstrap = (() => {\n` +
    `  const module = { exports: {} };\n` +
    `  const exports = module.exports;\n` +
    `  const require = window.require;\n` +
    normalized.trimEnd().split("\n").map((line) => line ? `  ${line}` : "").join("\n") + "\n" +
    `  return module.exports;\n` +
    `})();\n` +
    `${END}`;
}

function embed({ mainPath, sourcePath }) {
  const main = fs.readFileSync(mainPath, "utf8");
  const source = fs.readFileSync(sourcePath, "utf8");
  const block = buildBlock(source);
  let next;
  const start = main.indexOf(BEGIN);
  const finish = main.indexOf(END);
  if ((start >= 0) !== (finish >= 0) || (start >= 0 && finish < start)) {
    throw new Error("main.js 中 runtime bootstrap 标记不完整，拒绝覆盖");
  }
  if (start >= 0) {
    next = main.slice(0, start) + block + main.slice(finish + END.length);
  } else {
    const bannerEnd = main.indexOf("*/");
    if (bannerEnd < 0) throw new Error("main.js 缺少生成文件 banner，拒绝插入");
    next = main.slice(0, bannerEnd + 2) + "\n\n" + block + main.slice(bannerEnd + 2);
  }
  fs.writeFileSync(mainPath, next, "utf8");
  return { sourceSha256: sha256(source), mainSha256: sha256(next), bytes: Buffer.byteLength(next) };
}

if (require.main === module) {
  const root = path.resolve(__dirname, "..");
  const result = embed({
    mainPath: path.join(root, "main.js"),
    sourcePath: path.join(root, "tools", "runtime-bootstrap.js"),
  });
  process.stdout.write(JSON.stringify(result, null, 2) + "\n");
}

module.exports = { BEGIN, END, buildBlock, embed, sha256 };
