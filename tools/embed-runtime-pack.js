"use strict";

/**
 * Embed the verified Scholarium core runtime archive in main.js so an
 * Obsidian/GitHub plugin install is self-contained and never needs a second
 * network download. The generated block is deterministic and replaceable.
 *
 * Usage:
 *   node tools/embed-runtime-pack.js --main <main.js> --pack <core.tar.gz>
 */
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");

const BEGIN = "/* SCHOLARIUM_RUNTIME_PACK_EMBED_BEGIN */";
const END = "/* SCHOLARIUM_RUNTIME_PACK_EMBED_END */";
const BOOTSTRAP_END = "/* SCHOLARIUM_RUNTIME_BOOTSTRAP_EMBED_END */";
const EXPECTED = Object.freeze({
  version: "2.0.9-preview.4",
  platform: "win32-x64",
  file: "scholarium-runtime-core-2.0.9-preview.4-win32-x64.tar.gz",
  size: 57147381,
  sha256: "91c7e74e46c2da635a8092badefc072d93a48f6131155fd7be2eff1c296257f0",
});

function parseArgs(argv) {
  const args = {};
  for (let i = 2; i < argv.length; i += 2) args[argv[i].replace(/^--/, "")] = argv[i + 1];
  return args;
}

function sha256(buffer) {
  return crypto.createHash("sha256").update(buffer).digest("hex");
}

function generatedBlock(pack) {
  if (pack.length !== EXPECTED.size) throw new Error(`运行时包大小不符：${pack.length} != ${EXPECTED.size}`);
  const hash = sha256(pack);
  if (hash !== EXPECTED.sha256) throw new Error(`运行时包 SHA-256 不符：${hash}`);
  const encoded = pack.toString("base64");
  const chunks = [];
  for (let i = 0; i < encoded.length; i += 65536) chunks.push(JSON.stringify(encoded.slice(i, i + 65536)));
  return `${BEGIN}\n` +
    `// Generated by tools/embed-runtime-pack.js. Do not edit this payload by hand.\n` +
    `var SCH_EMBEDDED_RUNTIME_PACK = Object.freeze(${JSON.stringify(EXPECTED)});\n` +
    `var SCH_EMBEDDED_RUNTIME_PACK_BASE64 = [\n${chunks.map((chunk) => `  ${chunk}`).join(",\n")}\n].join("");\n` +
    `${END}`;
}

function embed({ mainPath, packPath }) {
  const source = fs.readFileSync(mainPath, "utf8");
  const block = generatedBlock(fs.readFileSync(packPath));
  let next;
  const start = source.indexOf(BEGIN), end = source.indexOf(END);
  if (start >= 0 || end >= 0) {
    if (start < 0 || end < start) throw new Error("main.js 的内置运行时标记不完整");
    next = source.slice(0, start) + block + source.slice(end + END.length);
  } else {
    const anchor = source.indexOf(BOOTSTRAP_END);
    if (anchor < 0) throw new Error("main.js 缺少 runtime bootstrap 插入点");
    const after = anchor + BOOTSTRAP_END.length;
    next = source.slice(0, after) + "\n\n" + block + source.slice(after);
  }
  fs.writeFileSync(mainPath, next, "utf8");
  return { mainPath, bytes: Buffer.byteLength(next), pack: EXPECTED };
}

if (require.main === module) {
  const args = parseArgs(process.argv);
  if (!args.main || !args.pack) {
    console.error("用法: node tools/embed-runtime-pack.js --main FILE --pack FILE");
    process.exit(2);
  }
  const result = embed({ mainPath: path.resolve(args.main), packPath: path.resolve(args.pack) });
  console.log(JSON.stringify(result));
}

module.exports = { embed, generatedBlock, EXPECTED, BEGIN, END };
